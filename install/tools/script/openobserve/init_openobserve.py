#!/usr/bin/env python3
"""Prepare local OpenObserve credentials and initialize its development organization."""

import argparse
import base64
import http.client
import json
import os
from pathlib import Path
import re
import secrets
import sys
import tempfile
import time
import urllib.error
import urllib.request


ORGANIZATION_PATTERN = re.compile(r"^[A-Za-z0-9_]+$")
EXPORTERS = (
    ("trace", "otlp_http/openobserve_trace", "atframework_traces"),
    ("metrics", "otlp_http/openobserve_metrics", "atframework_metrics"),
    ("logs", "otlp_http/openobserve_logs", "atframework_logs"),
    ("spanmetrics", "otlp_http/openobserve_spanmetrics", "atframework_metrics"),
)


def secure_file(path):
    if os.name == "posix":
        os.chmod(path, 0o600)


def read_password(path, create):
    path = Path(path)
    if path.exists():
        password = path.read_text(encoding="utf-8").strip()
        if not password:
            raise ValueError(f"OpenObserve password file is empty: {path}")
        if "\n" in password or "\r" in password or "\0" in password:
            raise ValueError(f"OpenObserve password file must contain one line: {path}")
        if len(password) > 128:
            raise ValueError(f"OpenObserve password exceeds 128 characters: {path}")
        secure_file(path)
        return password
    if not create:
        raise ValueError(f"OpenObserve password file does not exist: {path}")

    path.parent.mkdir(parents=True, exist_ok=True)
    # Keep 256 bits of randomness and guarantee upper/lowercase, digit, and symbol classes.
    password = secrets.token_urlsafe(32) + "aA9#"
    try:
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return read_password(path, False)
    with os.fdopen(descriptor, "w", encoding="utf-8") as output:
        output.write(password + "\n")
    secure_file(path)
    print(f"Created OpenObserve root password file: {path}", file=sys.stderr)
    return password


def yaml_string(value):
    return json.dumps(str(value), ensure_ascii=False)


def write_private_text(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix=path.name + ".", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as output:
            output.write(content)
        secure_file(temporary)
        os.replace(temporary, path)
        secure_file(path)
    finally:
        if temporary.exists():
            temporary.unlink()


def write_values(args, organization, password):
    token = base64.b64encode(f"{args.root_user_email}:{password}".encode("utf-8")).decode("ascii")
    endpoint = f"http://127.0.0.1:{args.http_port}/api/{organization}"
    # atdtool wraps values/modules/<name>.yaml in a top-level <name> key.
    lines = [
        "# Generated by openobserve.sh/.ps1. Contains local development credentials; do not commit.",
        "opentelemetry:",
        "  metrics:",
        "    prometheus:",
        "      http_api:",
        f"        url: {yaml_string(endpoint + '/prometheus/api/v1')}",
        "        headers:",
        "          - key: Authorization",
        f"            value: {yaml_string('Basic ' + token)}",
        "agent:",
        "  otelcol:",
        "    exporters:",
    ]
    for signal, exporter, stream in EXPORTERS:
        lines.extend((
            f"      {signal}:",
            f"        {exporter}:",
            f"          endpoint: {yaml_string(endpoint)}",
            "          headers:",
            f"            Authorization: {yaml_string('Basic ' + token)}",
            f"            stream-name: {yaml_string(stream)}",
        ))
    write_private_text(args.values_file, "\n".join(lines) + "\n")


def prepare(args):
    if not ORGANIZATION_PATTERN.fullmatch(args.organization):
        raise ValueError("organization must contain only ASCII letters, digits, and underscores")
    if not 1 <= args.http_port <= 65535:
        raise ValueError("HTTP port must be between 1 and 65535")
    if ":" in args.root_user_email or any(ord(c) < 32 for c in args.root_user_email):
        raise ValueError("root user email must not contain a colon or control characters")

    password = read_password(args.password_file, True)
    write_values(args, args.organization, password)
    print(password)


def basic_token(email, password):
    return base64.b64encode(f"{email}:{password}".encode("utf-8")).decode("ascii")


def response_error(response):
    body = response.read().decode("utf-8", errors="replace")[:1000]
    return f"HTTP {response.code}: {body}"


def api_request(opener, base_url, path, token, method="GET", payload=None, timeout=5):
    data = None
    headers = {"Accept": "application/json"}
    if token is not None:
        headers["Authorization"] = "Basic " + token
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    request = urllib.request.Request(base_url + path, data=data, headers=headers, method=method)
    with opener.open(request, timeout=timeout) as response:
        body = response.read().decode("utf-8")
        return json.loads(body) if body else None


def organization_identifier(opener, base_url, token, requested):
    result = api_request(opener, base_url, "/api/organizations", token)
    organizations = result.get("data", []) if isinstance(result, dict) else result
    if not isinstance(organizations, list):
        raise RuntimeError("OpenObserve returned an invalid organization list")
    for item in organizations:
        if isinstance(item, dict) and item.get("identifier") == requested:
            return requested
    matches = [item.get("identifier") for item in organizations
               if isinstance(item, dict) and item.get("name") == requested and item.get("identifier")]
    if len(matches) > 1:
        raise RuntimeError(f"OpenObserve returned multiple organizations named {requested!r}")
    return matches[0] if matches else None


def wait_for_organization(opener, base_url, token, requested, deadline, allow_missing=False):
    while True:
        try:
            identifier = organization_identifier(opener, base_url, token, requested)
            if identifier is not None or allow_missing:
                return identifier
            last_error = f"organization {requested!r} is not visible"
        except urllib.error.HTTPError as error:
            if error.code < 500:
                raise
            last_error = response_error(error)
        except (urllib.error.URLError, TimeoutError, ConnectionError, http.client.HTTPException) as error:
            last_error = str(error)
        if time.monotonic() >= deadline:
            raise RuntimeError(f"OpenObserve organization API did not become ready: {last_error}")
        time.sleep(min(1.0, max(0.05, deadline - time.monotonic())))


def initialize(args):
    password = read_password(args.password_file, False)
    token = basic_token(args.root_user_email, password)
    base_url = args.base_url.rstrip("/")
    # Never route loopback administration traffic through a developer's HTTP proxy.
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    deadline = time.monotonic() + args.startup_timeout
    last_error = "no health check was attempted"
    while True:
        try:
            health = api_request(opener, base_url, "/healthz", None, timeout=3)
            if isinstance(health, dict) and health.get("status") == "ok":
                break
            last_error = f"unexpected health response: {health!r}"
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, ValueError,
                ConnectionError, http.client.HTTPException) as error:
            last_error = str(error)
        if time.monotonic() >= deadline:
            raise RuntimeError(f"OpenObserve did not become healthy within {args.startup_timeout}s: {last_error}")
        time.sleep(min(1.0, max(0.05, deadline - time.monotonic())))

    identifier = wait_for_organization(opener, base_url, token, args.organization, deadline, allow_missing=True)
    created = False
    if identifier is None:
        try:
            api_request(
                opener,
                base_url,
                "/api/organizations",
                token,
                method="POST",
                payload={"name": args.organization, "identifier": args.organization, "org_type": "custom"},
            )
            created = True
        except urllib.error.HTTPError as error:
            # A concurrent initializer may have created it. Any other failure remains fatal.
            error_body = response_error(error)
            identifier = organization_identifier(opener, base_url, token, args.organization)
            if identifier is None:
                raise RuntimeError(f"failed to create organization {args.organization!r}: {error_body}") from error

    identifier = wait_for_organization(opener, base_url, token, args.organization, deadline)
    if args.values_file:
        write_values(args, identifier, password)
    state = "created" if created else "already present"
    print(f"OpenObserve organization {args.organization!r} is ready ({state}; identifier: {identifier}).")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    prepare_parser = subparsers.add_parser("prepare", help="create/reuse a password and write telemetry values")
    prepare_parser.add_argument("--password-file", required=True)
    prepare_parser.add_argument("--values-file", required=True)
    prepare_parser.add_argument("--root-user-email", default="admin@owent.net")
    prepare_parser.add_argument("--organization", default="atsf4g")
    prepare_parser.add_argument("--http-port", type=int, default=5080)
    prepare_parser.set_defaults(action=prepare)

    initialize_parser = subparsers.add_parser("initialize", help="wait for health and create the organization")
    initialize_parser.add_argument("--password-file", required=True)
    initialize_parser.add_argument("--root-user-email", default="admin@owent.net")
    initialize_parser.add_argument("--organization", default="atsf4g")
    initialize_parser.add_argument("--base-url", default="http://127.0.0.1:5080")
    initialize_parser.add_argument("--values-file")
    initialize_parser.add_argument("--http-port", type=int, default=5080)
    initialize_parser.add_argument("--startup-timeout", type=float, default=120)
    initialize_parser.set_defaults(action=initialize)

    args = parser.parse_args()
    try:
        args.action(args)
    except (OSError, RuntimeError, ValueError, urllib.error.URLError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
